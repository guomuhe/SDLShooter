# embed_assets.ps1
# Scan assets/ for read-only resources (exclude save.dat), embed them into
# obj\assets_data.o via ld -b binary, and generate src\assets_embed.cpp
# (extern symbol declarations + a path lookup table).
# Usage (from project root): powershell -ExecutionPolicy Bypass -File .\embed_assets.ps1
$ErrorActionPreference = 'Stop'

$proj      = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $proj
$assetsDir = "assets"
$outCpp    = "src\assets_embed.cpp"
$outObj    = "obj\assets_data.o"
$ld        = "d:\code\mingw32\bin\ld.exe"

if (-not (Test-Path "obj")) { New-Item -ItemType Directory -Path "obj" | Out-Null }
if (-not (Test-Path $ld)) { throw "ld.exe not found: $ld" }

# Collect resource files (exclude the writable save.dat)
$files = Get-ChildItem $assetsDir -Recurse -File | Where-Object { $_.Name -ne "save.dat" }
if ($files.Count -eq 0) { throw "assets directory is empty" }

function Get-Sym([string]$relPath) {
    return ($relPath -replace '[^A-Za-z0-9]', '_')
}

$map = New-Object System.Collections.Generic.List[object]
$inputPaths = New-Object System.Collections.Generic.List[string]
$seen = @{}
$rootLen = (Get-Location).Path.Length
foreach ($f in $files) {
    $rel = $f.FullName.Substring($rootLen + 1) -replace '\\','/'
    $sym = Get-Sym $rel
    if ($seen.ContainsKey($sym)) { throw "symbol clash: '$sym' from '$rel' and '$($seen[$sym])'" }
    $seen[$sym] = $rel
    $map.Add([PSCustomObject]@{ Path = $rel; Sym = $sym })
    $inputPaths.Add($rel)   # relative path passed to ld; symbol derives from this
}

# Embed every binary resource into a single .o
& $ld -r -b binary -o $outObj @inputPaths
if ($LASTEXITCODE -ne 0) { throw "ld -b binary failed (exit $LASTEXITCODE)" }

# Generate the lookup-table source (ASCII only; all asset paths are ASCII)
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('#include "assets_embed.h"')
$lines.Add('#include <unordered_map>')
$lines.Add('#include <string>')
$lines.Add('#include <utility>')
$lines.Add('#include <cstddef>')
$lines.Add('')
$lines.Add('// AUTO-GENERATED by embed_assets.ps1 -- do not edit by hand.')
$lines.Add('// Resource binaries are embedded into obj\assets_data.o via ld -b binary.')
$lines.Add('')
foreach ($e in $map) {
    $lines.Add("extern ""C"" const char binary_$($e.Sym)_start[];")
    $lines.Add("extern ""C"" const char binary_$($e.Sym)_end[];")
}
$lines.Add('')
$lines.Add('const unsigned char* FindEmbeddedAsset(const char* path, size_t* outSize)')
$lines.Add('{')
$lines.Add('    static const std::unordered_map<std::string, std::pair<const unsigned char*, size_t>> table = {')
foreach ($e in $map) {
    $esc = $e.Path -replace '\\','\\' -replace '"','\"'
    $lines.Add("        {`"$esc`", std::make_pair(reinterpret_cast<const unsigned char*>(binary_$($e.Sym)_start), static_cast<size_t>(binary_$($e.Sym)_end - binary_$($e.Sym)_start))},")
}
$lines.Add('    };')
$lines.Add('    if (path == nullptr) { if (outSize) *outSize = 0; return nullptr; }')
$lines.Add('    auto it = table.find(path);')
$lines.Add('    if (it == table.end()) { if (outSize) *outSize = 0; return nullptr; }')
$lines.Add('    if (outSize) *outSize = it->second.second;')
$lines.Add('    return it->second.first;')
$lines.Add('}')
$lines.Add('')

[System.IO.File]::WriteAllLines((Join-Path $proj $outCpp), $lines, [System.Text.Encoding]::ASCII)
Write-Host ("[embed_assets] embedded {0} resources -> {1} + {2}" -f $map.Count, $outObj, $outCpp) -ForegroundColor Green
